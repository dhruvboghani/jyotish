Chhath Puja is the great festival of the **Sun (Surya Dev)** and **Chhathi Maiya**, kept with deep devotion in Bihar, Jharkhand, eastern Uttar Pradesh, Nepal's Terai and by families from these regions everywhere. It is one of the strictest vrats in the Hindu calendar: the vratis fast for about 36 hours without water and offer arghya to both the setting and the rising Sun.

In 2026 Chhath falls from **Friday 13 to Monday 16 November**.

## Chhath Puja 2026 schedule

- **Day 1 – Nahay Khay, Fri 13 Nov (Chaturthi):** a holy bath and one pure, sattvic meal – usually rice, chana dal and lauki (bottle gourd) cooked in ghee without onion or garlic.
- **Day 2 – Kharna, Sat 14 Nov (Panchami):** fast through the day; after sunset the vrati eats gur-ki-kheer (rasiya) and roti, and the 36-hour nirjala fast begins.
- **Day 3 – Sandhya Arghya, Sun 15 Nov (Shashthi):** arghya to the setting Sun at a river, pond or ghat.
- **Day 4 – Usha Arghya, Mon 16 Nov (Saptami):** arghya to the rising Sun, then *parana* – the fast is broken with prasad.

## Arghya times

- **Patna:** sunset 17:01 on 15 Nov · sunrise 06:07 on 16 Nov
- **New Delhi:** sunset 17:27 on 15 Nov · sunrise 06:44 on 16 Nov

Shashthi tithi runs from 14 Nov 23:24 to 16 Nov 02:01. For other cities, open the [Panchang](/panchang/) and choose your location – the sunrise and sunset shown there are the arghya times.

## What goes in the soop (daura)

- **Thekua** – the signature prasad of wheat flour, jaggery and ghee
- Seasonal fruit: sugarcane, banana, coconut, sweet lime, sinhara (water chestnut), radish with leaves
- Rice laddoo (kasar), ginger and turmeric plants
- A diya and a few coins

Arghya is offered with milk and water from a copper or bamboo soop while standing in water and facing the Sun.

## Rules vratis follow

- Complete purity of food and kitchen – new or separately kept utensils, no onion or garlic in the house
- Sleep on the floor during the vrat
- Prasad is made by the vrati or close family, never tasted before it is offered
- The fast is broken only after the morning arghya

The Sun enters Vrishchika (Scorpio) on 16 November, the same morning as the Usha Arghya. To see where the Sun sits in your own chart, make your [free Kundali](/).
