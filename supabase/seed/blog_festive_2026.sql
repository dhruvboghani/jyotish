With the wedding season opening after Dev Uthani Ekadashi, many families ask the same question: *"How many gunas match?"* Gun Milan, or **Ashtakoot matching**, compares the **Moon's nakshatra and sign** in the two birth charts across eight factors (kootas). Together they carry **36 points (gunas)**.

## The eight kootas

1. **Varna – 1 point.** Spiritual temperament and ego compatibility, based on the Moon sign's element group.
2. **Vashya – 2 points.** Mutual attraction and who naturally influences whom.
3. **Tara – 3 points.** Counts from one nakshatra to the other; shows health, fortune and the flow of luck between the two.
4. **Yoni – 4 points.** Each nakshatra has an animal symbol; this measures physical and instinctive compatibility.
5. **Graha Maitri – 5 points.** Friendship between the lords of the two Moon signs – mental wavelength and day-to-day understanding.
6. **Gana – 6 points.** Deva, Manushya or Rakshasa nature – temperament and how conflicts are handled.
7. **Bhakoot – 7 points.** The distance between the two Moon signs; linked to family welfare, finances and love.
8. **Nadi – 8 points.** Aadi, Madhya or Antya – the highest-weighted koota, traditionally tied to health and progeny.

1 + 2 + 3 + 4 + 5 + 6 + 7 + 8 = **36**.

## How many gunas are enough?

- **Below 18:** generally not recommended without a deeper look at both charts
- **18 – 24:** acceptable, average match
- **25 – 32:** good match
- **33 – 36:** excellent – rare, and still not a guarantee on its own

A high score with a weak 7th house, or a low score with strong supporting factors, can change the picture completely. The score is the start of the conversation, not the verdict.

## Nadi dosha and Bhakoot dosha

**Nadi dosha** occurs when both partners have the same Nadi (0 of 8 points). **Bhakoot dosha** occurs when the Moon signs are 6–8, 9–5 or 2–12 from each other (0 of 7 points). Both are taken seriously – but classical texts list several **cancellations (parihara)**, for example:

- Both Moons in the same sign but in different nakshatras
- The same nakshatra but different Moon signs
- The lords of the two Moon signs are the same planet, or are friends
- For Bhakoot: the sign lords are mutual friends, or the Tara and Graha Maitri kootas are strong

So a "0 in Nadi" should never be read alone.

## What Gun Milan does not cover

Ashtakoot looks only at the Moon. A complete match also checks **Mangal Dosha** in both charts (see [Mangal Dosha: myths and facts](/blog/mangal-dosha-myths-and-facts/)), the strength of the **7th house** and its lord, Venus and Jupiter, and the running **Dasha** periods of both people around the wedding date.

