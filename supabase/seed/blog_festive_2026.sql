Dhanteras (Dhantrayodashi) opens the five days of Diwali. In 2026 it falls on **Friday, 6 November**. It honours Lord **Dhanvantari**, the physician of the gods who rose from the churning of the ocean holding a pot of amrit, and **Kubera** and **Lakshmi** as givers of wealth.

