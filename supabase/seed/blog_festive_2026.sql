## नाड़ी दोष और भकूट दोष

**नाड़ी दोष** तब होता है जब दोनों की नाड़ी एक ही हो (8 में से 0)। **भकूट दोष** तब होता है जब चंद्र राशियाँ एक-दूसरे से 6–8, 9–5 या 2–12 पर हों (7 में से 0)। दोनों को गंभीरता से लिया जाता है – पर शास्त्रों में कई **परिहार** भी बताए गए हैं, जैसे:

- दोनों का चंद्रमा एक ही राशि में पर अलग नक्षत्रों में
- एक ही नक्षत्र पर अलग चंद्र राशियाँ
- दोनों चंद्र राशियों का स्वामी एक ही ग्रह हो, या वे मित्र हों
- भकूट के लिए: राशि स्वामी परस्पर मित्र हों, या तारा और ग्रह मैत्री कूट मज़बूत हों

इसलिए "नाड़ी में 0" को कभी अकेले नहीं पढ़ना चाहिए।

## गुण मिलान क्या नहीं देखता

अष्टकूट केवल चंद्रमा को देखता है। पूरे मिलान में दोनों कुंडलियों का **मंगल दोष**, **सप्तम भाव** और उसके स्वामी की शक्ति, शुक्र और गुरु, और विवाह के आसपास दोनों की चल रही **दशा** भी देखी जाती है।

