## Why the puja is done in Pradosh Kaal

Pradosh is the window of about 2 hours 24 minutes after sunset. Dhanteras puja and **Yam Deepdaan** are done in this window because Trayodashi has to be present at dusk. In 2026 Trayodashi runs right through the evening of 6 November, so the whole Pradosh window is usable.

## Simple puja vidhi

1. Clean the house, especially the entrance and the puja corner, and draw a small rangoli at the door.
2. Place idols or pictures of Dhanvantari, Lakshmi, Ganesha and Kubera on a red or yellow cloth.
3. Light a ghee diya, offer roli, akshat, flowers, sweets and the new item you have bought.
4. Recite *Om Dhanvantaraye Namah* and the Lakshmi or Kubera mantra 11 or 108 times.
5. **Yam Deepdaan:** light a four-wicked diya of mustard oil and place it outside the main door, facing south, for the protection of the family.

## What to buy on Dhanteras

- **Gold or silver** – coins, jewellery or a small silver item
- **Brass, copper or steel utensils** – the classic Dhanteras purchase
- **A new broom** – believed to sweep away poverty and negativity
- **Whole coriander seeds (dhaniya)** – offered in puja and later sown or kept with savings
- **Gomti chakra, a Shri Yantra or Lakshmi-Ganesha idols** for Diwali puja

Many families avoid buying sharp objects, black items, glass and iron on this day. These are customs, not rules – follow your family tradition.

