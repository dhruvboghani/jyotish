## Why Sthir Lagna matters

The zodiac signs are grouped as movable, fixed and dual. **Vrishabha (Taurus)** is a fixed sign, ruled by Venus, the planet of comfort and prosperity. A puja begun when a fixed sign is rising is believed to give lasting results. On Diwali evening Vrishabha rises roughly between 6 and 8 pm in most of India, which is why that slot is so popular. Those who do Kali puja or tantric sadhana also use the **Simha (Leo)** lagna around midnight (Nishita Kaal).

## Lakshmi Puja vidhi, step by step

1. **Prepare:** clean the house, make rangoli, light diyas at the door and windows. Place a kalash with water, mango leaves and a coconut.
2. **Seat the deities:** on a red cloth, place Ganesha to the left and Lakshmi to the right, with Kubera and Saraswati if you wish. Keep account books, coins and jewellery in front.
3. **Sankalp:** take water in your right hand and state your name, gotra, place and the date, and your intention.
4. **Ganesha puja first,** then Lakshmi: offer water, roli, haldi, akshat, red flowers (lotus if available), kheel-batashe, sweets and fruit.
5. **Mantra:** *Om Shreem Hreem Shreem Kamale Kamalalaye Praseed Praseed* or simply *Om Mahalakshmyai Namah* – 108 times.
6. **Aarti:** sing *Om Jai Lakshmi Mata*, then light the main diya that stays lit through the night.
7. Distribute prasad and light diyas around the house.

