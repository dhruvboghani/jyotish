In the classical Vedic text *Brihat Parashara Hora Shastra*, Maharishi Parashara details the **Panch Mahapurusha Yogas**—five supreme combinations formed by the non-luminary planets that elevate a person to royal status, extraordinary mastery, and lasting fame.

If any of the five planets (Mars, Mercury, Jupiter, Venus, or Saturn) occupies a **Kendra house** (1st, 4th, 7th, or 10th) in its **own sign** or **exaltation sign**, one of these five royal yogas is born.

## 1. Ruchaka Yoga (Mars)
- **Condition:** Mars in Aries, Scorpio (own signs), or Capricorn (exaltation) in a Kendra.
- **Traits:** Exceptional physical courage, decisive leadership, athletic ability, and tactical brilliance.
- **Careers:** Defense personnel, police officers, surgeons, high-stakes entrepreneurs, real estate leaders.

## 2. Bhadra Yoga (Mercury)
- **Condition:** Mercury in Gemini (own sign) or Virgo (own and exaltation) in a Kendra.
- **Traits:** Sharp analytical intellect, eloquent speech, photographic memory, and business acumen.
- **Careers:** Writers, chartered accountants, data scientists, diplomats, software architects, traders.

## 3. Hamsa Yoga (Jupiter)
- **Condition:** Jupiter in Sagittarius, Pisces (own signs), or Cancer (exaltation) in a Kendra.
- **Traits:** High moral integrity, philosophical wisdom, benevolence, spiritual depth, and revered mentorship.
- **Careers:** Judges, university professors, spiritual teachers, financial advisors, statesmen.

## 4. Malavya Yoga (Venus)
- **Condition:** Venus in Taurus, Libra (own signs), or Pisces (exaltation) in a Kendra.
- **Traits:** Irresistible charm, aesthetic refinement, artistic mastery, wealth, and luxurious domestic comforts.
- **Careers:** Filmmakers, architects, luxury brand designers, performing artists, hospitality moguls.

## 5. Sasa Yoga (Saturn)
- **Condition:** Saturn in Capricorn, Aquarius (own signs), or Libra (exaltation) in a Kendra.
- **Traits:** Iron discipline, patient endurance, strategic foresight, mastery over logistics, and deep compassion for the common people.
- **Careers:** Industrialists, politicians, jurists, civil administrators, mining and infrastructure heads.

## When Do These Yogas Activate?

A Mahapurusha Yoga delivers its greatest fruits during the **Mahadasha and Antardasha** of the planet forming it. However, the yoga must not be combust by the Sun or heavily afflicted by malefic aspects, as that dilutes the physical manifestation of its blessings.

