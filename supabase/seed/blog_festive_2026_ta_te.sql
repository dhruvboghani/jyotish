ராசிகள் சர, ஸ்திர, உபய என மூன்று வகை. **ரிஷபம்** சுக்கிரன் ஆளும் ஸ்திர ராசி – சுகம், செல்வத்தின் கிரகம். ஸ்திர லக்னத்தில் தொடங்கும் பூஜையின் பலன் நிலைத்து நிற்கும் என்பது நம்பிக்கை – லட்சுமி வீட்டில் "நிலைத்து" இருப்பதற்காக.

## லட்சுமி பூஜை முறை

1. **ஏற்பாடு:** வீட்டை சுத்தம் செய்து கோலம் போட்டு வாசலிலும் ஜன்னல்களிலும் விளக்கேற்றுங்கள். நீர், மாவிலை, தேங்காயுடன் கலசம் வையுங்கள்.
2. **பிரதிஷ்டை:** சிவப்புத் துணியில் இடப்புறம் விநாயகர், வலப்புறம் லட்சுமி. முன்னால் கணக்குப் புத்தகங்கள், நாணயங்கள், நகைகள்.
3. **சங்கல்பம்:** வலது கையில் நீர் எடுத்து பெயர், கோத்திரம், இடம், தேதி, வேண்டுதலைச் சொல்லுங்கள்.
4. **முதலில் விநாயகர் பூஜை**, பிறகு லட்சுமி: நீர், குங்குமம், மஞ்சள், அட்சதை, சிவப்பு மலர்கள் (தாமரை கிடைத்தால் சிறப்பு), இனிப்பு, பழங்கள்.
5. **மந்திரம்:** *ஓம் ஸ்ரீம் ஹ்ரீம் ஸ்ரீம் கமலே கமலாலயே ப்ரஸீத ப்ரஸீத* அல்லது *ஓம் மகாலட்சுமியை நமஹ* – 108 முறை.
6. **ஆரத்தி** எடுத்து, இரவு முழுவதும் எரியும் பெரிய விளக்கை ஏற்றுங்கள்.
7. பிரசாதம் வழங்கி வீடு முழுவதும் தீபம் ஏற்றுங்கள்.

