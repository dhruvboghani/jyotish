## பூஜை ஏன் பிரதோஷ காலத்தில்?

சூரியன் மறைந்த பின் சுமார் 2 மணி 24 நிமிடம் பிரதோஷ காலம். அந்தி நேரத்தில் திரயோதசி இருக்க வேண்டும் என்பதால் தன்தேரஸ் பூஜையும் **யம தீபமும்** இந்த நேரத்தில் செய்யப்படுகின்றன. 2026 இல் 6 நவம்பர் மாலை முழுவதும் திரயோதசி இருப்பதால் முழு பிரதோஷ காலமும் உகந்தது.

## எளிய பூஜை முறை

1. வீட்டையும், குறிப்பாக வாசலையும் பூஜை அறையையும் சுத்தம் செய்து வாசலில் கோலம் போடுங்கள்.
2. சிவப்பு அல்லது மஞ்சள் துணியில் தன்வந்திரி, லட்சுமி, விநாயகர், குபேரன் படங்களை வையுங்கள்.
3. நெய் விளக்கேற்றி, குங்குமம், அட்சதை, மலர், இனிப்பு மற்றும் புதிதாக வாங்கிய பொருளை வைத்து வழிபடுங்கள்.
4. *ஓம் தன்வந்தரயே நமஹ* மற்றும் லட்சுமி அல்லது குபேர மந்திரத்தை 11 அல்லது 108 முறை ஜபியுங்கள்.
5. **யம தீபம்:** கடுகு எண்ணெயில் நான்கு திரி விளக்கேற்றி வாசலுக்கு வெளியே தெற்கு நோக்கி வையுங்கள் – குடும்பத்தின் பாதுகாப்புக்காக.

## தன்தேரஸில் என்ன வாங்கலாம்

- **தங்கம் அல்லது வெள்ளி** – நாணயம், நகை அல்லது சிறிய வெள்ளிப் பொருள்
- **பித்தளை, செம்பு அல்லது எவர்சில்வர் பாத்திரங்கள்**
- **புதிய துடைப்பம்** – வறுமையையும் எதிர்மறையையும் விலக்கும் என்பது நம்பிக்கை
- **முழு கொத்தமல்லி விதை** – பூஜையில் வைத்து பின்னர் விதைக்கலாம் அல்லது சேமிப்புடன் வைக்கலாம்
- **ஸ்ரீ யந்திரம், லட்சுமி-விநாயகர் சிலைகள்** தீபாவளி பூஜைக்கு

பல குடும்பங்கள் இந்த நாளில் கூர்மையான பொருட்கள், கருப்புப் பொருட்கள், கண்ணாடி, இரும்பு வாங்குவதில்லை. இவை மரபுகள், கட்டாய விதிகள் அல்ல – உங்கள் குடும்ப வழக்கத்தைப் பின்பற்றுங்கள்.

