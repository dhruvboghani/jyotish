## పూజ ప్రదోష కాలంలో ఎందుకు?

సూర్యాస్తమయం తర్వాత సుమారు 2 గంటల 24 నిమిషాలు ప్రదోష కాలం. సంధ్యా సమయంలో త్రయోదశి ఉండాలి కాబట్టి ధన త్రయోదశి పూజ, **యమ దీపం** ఈ సమయంలోనే చేస్తారు. 2026లో 6 నవంబర్ సాయంత్రం అంతా త్రయోదశి ఉంది, కాబట్టి ప్రదోష కాలం మొత్తం శుభప్రదం.

## సులభమైన పూజా విధానం

1. ఇల్లు, ముఖ్యంగా గుమ్మం, పూజా గది శుభ్రం చేసి ముగ్గు వేయండి.
2. ఎరుపు లేదా పసుపు వస్త్రంపై ధన్వంతరి, లక్ష్మి, గణపతి, కుబేరుల చిత్రాలు ఉంచండి.
3. నెయ్యి దీపం వెలిగించి, కుంకుమ, అక్షతలు, పువ్వులు, మిఠాయి, కొత్తగా కొన్న వస్తువు సమర్పించండి.
4. *ఓం ధన్వంతరయే నమః* మరియు లక్ష్మి లేదా కుబేర మంత్రాన్ని 11 లేదా 108 సార్లు జపించండి.
5. **యమ దీపం:** ఆవనూనెతో నాలుగు వత్తుల దీపం వెలిగించి గుమ్మం బయట దక్షిణ దిశగా ఉంచండి – కుటుంబ రక్షణ కోసం.

