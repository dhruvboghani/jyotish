ఇద్దరిదీ ఒకే నాడీ అయితే **నాడీ దోషం** (8లో 0). చంద్ర రాశులు 6–8, 9–5 లేదా 2–12 స్థానాల్లో ఉంటే **భకూట దోషం** (7లో 0). అయితే శాస్త్రాలు ఎన్నో **పరిహారాలు (మినహాయింపులు)** చెబుతాయి:

- ఇద్దరి చంద్రుడు ఒకే రాశిలో, వేర్వేరు నక్షత్రాల్లో
- ఒకే నక్షత్రం, వేర్వేరు రాశులు
- రెండు రాశుల అధిపతి ఒకే గ్రహం లేదా మిత్రులు
- భకూట కోసం: రాశి అధిపతులు పరస్పర మిత్రులు, లేదా తారా, గ్రహ మైత్రి బలంగా ఉంటే

