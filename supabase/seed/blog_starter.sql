Why do some years feel like everything clicks, and others like wading through mud? In Jyotish, the answer usually lies in the **dasha** you are running.

## A 120-year cycle

Vimshottari dasha divides life into periods ruled by the nine grahas, in a fixed order with fixed lengths:

- Ketu 7 years → Venus 20 → Sun 6 → Moon 10 → Mars 7
- Rahu 18 → Jupiter 16 → Saturn 19 → Mercury 17

Together they add up to 120 years.

## Where does yours start?

Your **birth nakshatra** (the Moon's star) decides which dasha you are born into, and how much of it is left. Someone born with the Moon in Rohini starts in Moon dasha; someone in Magha starts in Ketu dasha. That is why the exact birth time and Moon position matter.

## Mahadasha, antardasha and pratyantar

Each **mahadasha** is split into nine **antardashas** (bhuktis) in the same order, starting with the mahadasha lord itself. Each antardasha is split again into pratyantar dashas. The mahadasha sets the theme of years; the antardasha sets the theme of months.

## How to read a dasha

Ask three questions about the dasha lord in your chart:

1. **Which houses does it rule?** Those areas of life become active.
2. **Where does it sit, and with whom?** That colours how results come.
3. **How strong is it?** A strong, well-placed lord gives results easily; a weak one gives them with effort.

Transits of Jupiter and Saturn then act as the trigger that brings the dasha's promise into a specific year.

