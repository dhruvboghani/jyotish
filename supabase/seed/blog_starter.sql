A gemstone (ratna) is one of the most popular remedies, and one of the most misused. The key idea is simple: **a gemstone strengthens its planet.** It does not make a harmful planet kind.

## The planets and their stones

- Sun: Ruby (Manik) · Moon: Pearl (Moti) · Mars: Red Coral (Moonga)
- Mercury: Emerald (Panna) · Jupiter: Yellow Sapphire (Pukhraj) · Venus: Diamond (Heera)
- Saturn: Blue Sapphire (Neelam) · Rahu: Hessonite (Gomed) · Ketu: Cat's Eye (Lehsunia)

## When a gemstone helps

Wear a stone when its planet is **good for your lagna** (it rules kendras or trikonas) but is **weak** in your chart: low in strength, combust or poorly placed. Strengthening such a planet brings its good results more easily.

## When to avoid it

- The planet rules the 6th, 8th or 12th house for your lagna. Strengthening it can increase problems.
- The planet is already very strong. More strength rarely helps.
- Blue Sapphire, Hessonite and Cat's Eye act fast and strongly. Try them only after careful study, ideally for a trial period.

## Wearing it properly

Traditionally a stone is set in the right metal, worn on the right finger on its planet's weekday during a good hora, after a short mantra. A natural, untreated stone of reasonable size matters more than a large one.

## Safer remedies first

Mantra, charity linked to the planet, fasting and simple discipline work for every chart and never harm. Many astrologers recommend them before any gemstone.

