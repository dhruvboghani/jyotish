Few words worry people in India as much as **Sade Sati**. Yet it is simply a period when Saturn (Shani) moves through three signs around your Moon sign. Understanding it takes away most of the fear.

## When does Sade Sati happen?

Saturn takes about 2½ years to cross one sign. Sade Sati begins when Saturn enters the sign **just before** your Moon sign (your rashi), continues while it is **in** your Moon sign, and ends when it leaves the sign **just after** it. Three signs × 2½ years = about 7½ years, which is what *sade sati* means.

Because Saturn returns roughly every 29–30 years, most people meet Sade Sati two or three times in a lifetime.

## The three phases

1. **Rising phase (12th from the Moon):** expenses, travel, sleep and a feeling of things slipping away. A good time to cut waste and finish old work.
2. **Peak phase (over the Moon):** the most felt part. Pressure on the mind, family duties and patience. Health and routine need care.
3. **Setting phase (2nd from the Moon):** money and family speech are tested, but results of hard work start to show.

## Is it always bad?

No. Saturn rewards discipline, honesty and steady work. People often build their careers, buy property or take on bigger roles during Sade Sati, because Saturn makes us serious. How it feels depends on Saturn's strength in your own chart, your running dasha and the houses involved, not only on the Moon sign.

> If Saturn is a yogakaraka for your lagna (Vrishabha and Tula lagna), Sade Sati is often productive rather than painful.

## Practical remedies

- Keep a simple routine: sleep, food and work on time. Saturn loves discipline.
- Help those who work hard for little: labourers, the elderly, the disabled.
- On Saturdays, light a sesame-oil lamp and recite the Shani mantra or Hanuman Chalisa.
- Avoid shortcuts, debts you cannot repay and quarrels with seniors.

