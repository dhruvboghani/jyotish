"Is the boy or girl Manglik?" is often the first question in a marriage talk. Mangal Dosha is real in Jyotish, but it is far more common, and far less frightening, than most people think.

## What is Mangal Dosha?

Mars (Mangal) is said to give Mangal Dosha when it sits in the **1st, 2nd, 4th, 7th, 8th or 12th house**. Many astrologers check this from the lagna, from the Moon and from Venus. Counted this way, roughly half of all people have some form of it, which already shows it cannot mean every such marriage is in trouble.

## Why Mars in these houses?

Mars is energy, courage and temper. In houses linked with home, partner, family speech and intimacy, strong Mars can show impatience, arguments or a very independent nature. It describes *temperament*, not destiny.

## Common cancellation rules

Classical texts give many conditions under which the dosha is cancelled or greatly reduced, for example:

- Both partners have Mangal Dosha.
- Mars is in its own sign (Mesha, Vrishchika) or exalted (Makara).
- Jupiter aspects Mars or the 7th house.
- Mars is in the 2nd house in Mithuna or Kanya, or in the 12th in Vrishabha or Tula (rules vary by tradition).
- Saturn, Rahu or Ketu also sit in the same houses for the other partner.

## What matters more in matching

Mangal Dosha is one factor. A good match also looks at the Ashtakoot (36 guna) score, Nadi and Bhakoot doshas, the 7th house and its lord, Venus, and the dashas each person will run after marriage. Most of all, it looks at two people's values and maturity.

